import { config } from 'dotenv';
import { spawnSync } from 'node:child_process';
import { mkdirSync, chmodSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
config({path:new URL('../server/.env',import.meta.url)});
if(!process.env.DATABASE_URL)throw new Error('DATABASE_URL не настроен');
const url=new URL(process.env.DATABASE_URL);
if(!['postgres:','postgresql:'].includes(url.protocol))throw new Error('Ожидается PostgreSQL');
const target=resolve(process.argv[2] ?? `/var/backups/karlo-wear/karlo-${new Date().toISOString().replaceAll(':','-')}.dump`);
mkdirSync(dirname(target),{recursive:true,mode:0o700});
const env={...process.env,PGHOST:url.hostname,PGPORT:url.port||'5432',PGUSER:decodeURIComponent(url.username),PGPASSWORD:decodeURIComponent(url.password),PGDATABASE:decodeURIComponent(url.pathname.slice(1)),PGSSLMODE:url.searchParams.get('sslmode')||'prefer'};
const result=spawnSync('pg_dump',['--format=custom','--file',target],{env,stdio:'inherit',windowsHide:true});
if(result.error)throw result.error;
if(result.status!==0)process.exit(result.status||1);
chmodSync(target,0o600);
const verify=spawnSync('pg_restore',['--list',target],{env,stdio:['ignore','ignore','inherit'],windowsHide:true});
if(verify.error)throw verify.error;
if(verify.status!==0)process.exit(verify.status||1);
console.log('Резервная копия PostgreSQL проверена:',target);
